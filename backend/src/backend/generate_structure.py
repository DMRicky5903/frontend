from pathlib import Path


BACKEND_ROOT = Path(__file__).resolve().parent.parent.parent

SRC_DIR = BACKEND_ROOT / "src"
DOCS_DIR = BACKEND_ROOT / "docs"
OUTPUT_FILE = DOCS_DIR / "STRUCTURE.md"

SCRIPT_FILE = Path(__file__).resolve()

IGNORED_NAMES = {
    ".DS_Store",
    ".env",
    ".env.local",
    ".git",
    ".gitignore",
    ".mypy_cache",
    ".pytest_cache",
    ".ruff_cache",
    ".uv",
    ".uv-cache",
    ".venv",
    "__pycache__",
    "build",
    "coverage",
    "dist",
    "logs",
    "node_modules",
    "tmp",
    "uploads",
}

IGNORED_SUFFIXES = {
    ".pyc",
    ".pyo",
    ".log",
    ".tmp",
}


def should_ignore(path: Path) -> bool:
    if path == SCRIPT_FILE:
        return True

    if path.name in IGNORED_NAMES:
        return True

    if path.suffix.lower() in IGNORED_SUFFIXES:
        return True

    return False


def build_tree(directory: Path, prefix: str = "") -> list[str]:
    entries = sorted(
        (entry for entry in directory.iterdir() if not should_ignore(entry)),
        key=lambda entry: (not entry.is_dir(), entry.name.lower()),
    )

    lines: list[str] = []

    for index, entry in enumerate(entries):
        is_last = index == len(entries) - 1
        connector = "└── " if is_last else "├── "
        next_prefix = "    " if is_last else "│   "

        lines.append(f"{prefix}{connector}{entry.name}")

        if entry.is_dir():
            lines.extend(build_tree(entry, prefix + next_prefix))

    return lines


def generate() -> None:
    if not SRC_DIR.is_dir():
        raise SystemExit(f"src directory not found: {SRC_DIR}")

    tree_lines = ["src/", *build_tree(SRC_DIR)]
    tree = "\n".join(tree_lines)

    content = f"""# Project Structure

> Auto-generated by `uv run docs-structure`.
> Do not edit this file manually.

```text
{tree}
```
"""

    OUTPUT_FILE.write_text(content)
    print(f"Project structure generated at: {OUTPUT_FILE}")
if __name__ == "__main__":
    generate()