import { readdirSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { join, relative } from "node:path";

const ROOT = process.cwd();
const SRC_DIR = join(ROOT, "src");
const OUTPUT_FILE = join(ROOT, "docs", "STRUCTURE.md");

const IGNORED = new Set([
  "node_modules",
  ".git",
  "dist",
  "build",
  "coverage",
  ".DS_Store",
]);

function buildTree(dir, prefix = "") {
  const entries = readdirSync(dir)
    .filter((name) => !IGNORED.has(name))
    .sort((a, b) => {
      const aIsDir = statSync(join(dir, a)).isDirectory();
      const bIsDir = statSync(join(dir, b)).isDirectory();

      if (aIsDir && !bIsDir) return -1;
      if (!aIsDir && bIsDir) return 1;
      return a.localeCompare(b);
    });

  const lines = [];

  entries.forEach((entry, index) => {
    const fullPath = join(dir, entry);
    const isLast = index === entries.length - 1;
    const connector = isLast ? "└── " : "├── ";
    const nextPrefix = isLast ? "    " : "│   ";

    lines.push(`${prefix}${connector}${entry}`);

    if (statSync(fullPath).isDirectory()) {
      lines.push(...buildTree(fullPath, `${prefix}${nextPrefix}`));
    }
  });

  return lines;
}

function generate() {
  if (!statSync(SRC_DIR).isDirectory()) {
    throw new Error("src directory not found");
  }

  const tree = ["src/", ...buildTree(SRC_DIR)].join("\n");

  const content = `# Project Structure

> Auto-generated by \`npm run docs:structure\`. Do not edit manually.

\`\`\`text
${tree}
\`\`\`
`;

  mkdirSync(join(ROOT, "docs"), { recursive: true });
  writeFileSync(OUTPUT_FILE, content, "utf8");

  console.log(`Generated: ${relative(ROOT, OUTPUT_FILE)}`);
}

generate();
